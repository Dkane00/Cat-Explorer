    val all: List<Theme> = listOf(Theme(DEFAULT, catExplorer)) +
        js8.map { (name, stops) -> Theme(name, build(FloatArray(stops.size) { it / (stops.size - 1f) }, stops)) }

    fun named(name: String?): Theme = all.firstOrNull { it.name == name } ?: all[0]

    /** 256 opaque colours, linear between [stops] at positions [at] (0..1). */
    private fun build(at: FloatArray, stops: IntArray) = IntArray(256) { i ->
        val t = i / 255f
        val k = at.indexOfLast { it <= t }.coerceIn(0, at.size - 2)
        val u = ((t - at[k]) / (at[k + 1] - at[k])).coerceIn(0f, 1f)
        fun ch(c: Int, s: Int) = (c shr s) and 0xFF
        fun mix(s: Int) = (ch(stops[k], s) + (ch(stops[k + 1], s) - ch(stops[k], s)) * u).toInt()
        (0xFF shl 24) or (mix(16) shl 16) or (mix(8) shl 8) or mix(0)
    }
